export function translate(key: string, language: Language): string {
  return translations[language][key] ?? translations.en[key] ?? key;
}

export interface TranslationServiceAdapter {
  translate(text: string, language: Language): Promise<string>;
}

export function createTranslationServiceAdapter(
  remoteTranslate?: (text: string, language: Language) => Promise<string>,
): TranslationServiceAdapter {
  return {
    async translate(text, language) {
      if (!remoteTranslate) return translate(text, language);
      try {
        return await remoteTranslate(text, language);
      } catch (error) {
        console.warn('Remote translation failed; using local language resources.', error);
        return translate(text, language);
      }
    },
  };
}

